      curl -sL --max-time 1200 -o "${'$'}tmp" "${'$'}url"
      actual="${'$'}(sha256sum "${'$'}tmp" | awk '{print ${'$'}1}')"
      if [ "${'$'}actual" != "${'$'}expected" ]; then
