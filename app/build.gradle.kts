// #423: one source of truth classifies every JVM test into exactly one public
// verification partition. Gradle and the local changed-test selector both
// consume this CLI, so a new test cannot silently disappear between them.
fun partitionTestClasses(
  partition: String,
  cohort: String = "all",
): List<String> {
  val arguments = mutableListOf(
    rootProject.file("scripts/test_partitions.py").absolutePath,
    "--root",
    rootProject.projectDir.absolutePath,
    "list",
    "--partition",
    partition,
    "--cohort",
    cohort,
  )
  return providers.exec {
    workingDir(rootProject.projectDir)
    commandLine("python3", *arguments.toTypedArray())
  }.standardOutput.asText.get().lineSequence().filter(String::isNotBlank).toList()
}

// The classifier shells out to Python and reads every test source, so resolve
// the lists lazily: a build pays for at most the one partition it runs, and
// non-test invocations (assemble, install, IDE sync) pay nothing at all.
fun partitionClasses(partition: String, cohort: String = "all"): Provider<List<String>> =
  providers.provider { partitionTestClasses(partition, cohort) }

