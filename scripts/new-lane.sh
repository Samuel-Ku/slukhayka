#!/usr/bin/env bash
#
# Одна команда замість трьох ручних: резервує тікет, бере свіжий `origin/main`,
# створює копію смуги й друкує факти для брифа.
#
# Навіщо. Усе в цьому репозиторії має скрипт — премиса, числа, межі, сторожі,
# бюджет, час, мердж, вердикт, — а диспетчеризація смуги була трьома командами
# руками. Саме там сталися ВСІ координаційні помилки серії: чотири хибні числа
# в брифи (бо їх згадували, а не брали командою), дві смуги в одній копії
# (`commit --amend`, `reset --hard`, стерті правки) і хибна база виміру після
# squash (`--ff-only` не спрацював, і міряли дерево гілки, не `main`). Жоден
# наявний гейт цього не ловив: усі вони дивляться на КОД, а помилки були в
# ПРОЦЕСІ. Тут процес і отримує механізм.
#
# Що робить:
#   1) `git fetch origin main` — свіжа база, а не поточний HEAD;
#   2) резервує тікет НАЯВНИМ `scripts/agent-work-claim.py` (нового механізму
#      немає; зайнятий тікет — код 2 і КОПІЇ НЕ СТВОРЕНО);
#   3) створює `.worktrees/w<номер>` від `origin/main`, гілкою `t<номер>-<slug>`
#      (з `--no-track`: інакше гілка смуги «відстежує» `origin/main`, і
#      `git status` бреше про базу — та сама хибна база, тільки тихіша);
#   4) перевіряє ПРЕМИСУ ТІКЕТА наявним `scripts/issue_premise.py --issue` —
#      застарілий тікет названо у фактах ДО роботи, а не після витраченого часу
#      (#1324). Знахідка (код 1) і невідомість вердикту (код 2) — попередження
#      зі збереженням смуги; код 2 САМОЇ СМУГИ лишається за станом, коли тікет
#      не прочитано і вердикту немає взагалі;
#   5) переносить `local.properties` з кореня робочої копії в копію смуги, якщо
#      він там є (#1332), — і НАЗИВАЄ це у фактах; немає файлу — теж названо, і
#      чому саме Android-збірка в цій копії не працюватиме;
#   6) друкує ФАКТИ ДЛЯ БРИФА — їх вставляють, а не згадують: гілку, базу
#      (`sha`), скільки записів у реєстрі сторожів (`--count`, а не рядків
#      `--list`), ліміт джоби, премису тікета й команди, які смуга проганяє сама.
#
# Виклик:
#   scripts/new-lane.sh <номер> <slug>
#   scripts/new-lane.sh --release <номер>
#
# `--release` — гігієна копій після мерджу: прибирає копію смуги, коли в ній
# нема чого втрачати. Гілку не видаляє НІКОЛИ (та сама межа, що в
# `merge-pr.sh`), резервування не чіпає (його знімає координатор — доки тікет
# не закрито, запис лишається).
#
# Межі названі тут, у коді, а не лише в звіті:
#   * `--release` не спрацьовує сам після мерджу, і це навмисно. Мердж-гейт не
#     знає, чия копія і чи не тримає вона правок огляду; `git worktree remove`
#     без `--force` відмовляє на брудному дереві, тож автоматичне прибирання з
#     чужого процесу або мовчки не робило б нічого, або вимагало б `--force`,
#     який стирає чужу роботу. Прибирає координатор ЯВНО — і рівно тоді, коли
#     переконався, що правок немає;
#   * гілку не видаляє жодна вітка цього скрипта: `t<номер>-<slug>` лишається
#     в `refs/heads`, як і після `merge-pr.sh`. Названа й ціна цієї межі: якщо
#     `switch -c` упаде ВЖЕ після запису ref'а, гілка лишиться, і наступна
#     спроба впреться в «гілка вже існує». Це вузьке вікно (ref пишеться
#     останнім кроком, коли все вже перевірено), і видаляти гілку тут означало б
#     завести прибирання чужого ref'а — тому межа названа, а не замовчана;
#   * `--release` читає `git` у копії ЛИШЕ коли копія — ЖИВИЙ чекаут смуги:
#     `worktree_live` вимагає запису без позначки `prunable`, а `lane_is_checkout`
#     — щоб `rev-parse --show-toplevel` у ній дорівнював їй самій. Обидві
#     перевірки потрібні, і ось чому: незареєстрована тека І застарілий
#     (prunable) запис із текою, створеною знову на тому ж шляху, однаково
#     змусили б `git -C` піднятися до БАТЬКІВСЬКОГО репозиторію й прочитати
#     дерево КООРДИНАТОРА (той самий клас, проти якого цей скрипт і писався).
#     Такий шлях скрипт або прибирає (порожню теку — `rmdir`, застарілий запис —
#     `worktree prune`), або не чіпає й каже про це; живого запису, що не є
#     чекаутом, він не чіпає взагалі — це стан, якого ми не розуміємо;
#   * механізм стає РОБОЧИМ ПІСЛЯ МЕРДЖУ, і це названо, а не замовчано: факти
#     беруться з КОПІЇ (`guard_witnesses.py --count`, `ci_job_time.py --list`), а
#     копія — це `origin/main`. Проти бази БЕЗ цього тікета створення падає
#     раніше — `guard_witnesses.py: error: unrecognized arguments: --count` — і
#     чисто відкочується (копії, резервування й гілки не лишається). Тести цього
#     не бачать: фікстура копіює скрипти з дерева самого PR, тож перевіряють
#     майбутню базу, а не сьогоднішню;
#   * резервування не знімається автоматично: у `agent-work-claim.py` навмисно
#     немає примусового звільнення, і цей скрипт його не вигадує. Він лише
#     НАЗИВАЄ шлях запису;
#   * власника резервування скрипт не вигадує: без `--owner`/`NEW_LANE_OWNER`
#     (або `DSH_SESSION_ID` у цьому середовищі) він відмовляє, бо запис із
#     вигаданим власником — це та сама обіцянка в прозі;
#   * `local.properties` переносить САМЕ ЦЕЙ крок, і джерело в нього одне —
#     корінь робочої копії (`NEW_LANE_REPO`, якщо названо), тобто рівно те, що
#     робив ручний рецепт `docs/agents/local-environment.md`:
#     `cp local.properties .worktrees/<lane>/local.properties`. Це не «нова
#     діра», а крок, який ЗАГУБИВСЯ при автоматизації (#1332): файл лежить у
#     `.gitignore`, тож у копію сам не потрапляє, а без нього Android-збірка
#     падає `SDK location not found` — смуга #1187 через це втратила прогін.
#     Немає файлу — НЕ відмова: факти називають, що Android-збірка в цій копії
#     не працюватиме, і чому. Збій копіювання наявного файлу — навпаки,
#     невідомість, і вона відкочується: покласти копію й не сказати про збій
#     було б тим самим «запис каже одне, реальність — інше»;
#   * поле `plan` у резервуванні називає ЛИШЕ той шлях, який уже існує в базі
#     смуги (`origin/main`) ЯК ФАЙЛ, або `null` (#1337, #1340). До #1337 крок
#     ВИГАДУВАВ
#     `docs/plans/<дата>-<номер>-<slug>.md`; переміряно на шести записах
#     кореневої копії: п'ять шляхів `docs/plans/…` — і ЖОДНОГО з них немає
#     (шостий запис вказує на наявну спеку). Плану
#     смуги на момент створення ще немає, тож типове значення — `null`, і факти
#     це друкують. Шлях, названий явно (`--plan`/`NEW_LANE_PLAN`),
#     перевіряється ДО резервування: неіснуючий — відмова (код 2), бо саме
#     неіснуючий шлях у записі й був дефектом. #1340 назвав другий бік тієї самої
#     межі: `git cat-file -e` відповідає «об'єкт існує», а ДЕРЕВО теж об'єкт —
#     `--plan docs` проходив перевірку й потрапляв у запис, хоч тека не є планом
#     (твердження поля виконувалося, а сенс — ні). Тому питається ТИП
#     (`cat-file -t`), і планом вважається ЛИШЕ `blob` (файл): `tree`, `commit`
#     і `tag` — відмова з названим типом, а не «шлях начебто є». Це один вибір —
#     «у записі лише те, що справді є ФАЙЛОМ», — а не півзахід: обидві вітки
#     дають ту саму межу. Плану скрипт не створює: порожній файл — не план, і
#     механізм не вдає, що його написав;
#   * відкат прибирає запис резервування лише тоді, коли той НАШ, і каже ПРАВДУ
#     про те, що лишилося (#1340). «Наш» — це РОЗІБРАНИЙ JSON, а не рядок файлу:
#     `grep -Fq "\"reservation\": \"$RESERVATION\""` не бачив назви з лапкою, бо
#     `json.dump` екранує її як `\"`, — і файл лишався на диску, хоч
#     повідомлення казало «резервування прибрано». Ціна саме цієї брехні
#     найбільша: координатор, який бачить «прибрано», піднімає другу смугу на
#     зайнятий тікет. Другий бік тієї самої межі: після спроби видалення файл
#     перевіряється ЩЕ РАЗ, і факт про нього ставить сам відкат — якщо запис
#     лишився (чужий, нерозібраний або його не вдалося прибрати), це НАЗВАНО,
#     а не замовчано. Примусового звільнення тут немає: чужий запис лишається
#     чужим;
#   * ТЕКУ смуги відкат перевіряє тим самим способом (#1343). До цього факт про
#     запис був, а факт про теку — ні: шість повідомлень казали «копію
#     прибрано», ще два — «копії й гілки немає», і всі вісім спиралися на код
#     виходу `git worktree remove`. Координатор, який їх бачив, вважав місце
#     вільним, хоч тека лишалася. Fail-closed (друга смуга в ту саму теку не
#     сяде), але той самий клас, що закрив #1340. Тепер `ROLLBACK_LANE_FACT`
#     ставить сам відкат ПІСЛЯ спроби, питаючи ДИСК (`lane_present`), а кожне
#     місце виклику друкує ОБИДВА факти. Заміряно ін'єкцією: `git worktree
#     remove`, який виходить нулем і не прибирає теку, і відмова з кодом —
#     обидва названі «копія ЛИШИЛАСЯ» з причиною. Межа лишається названою:
#     відкат прибирає ЛИШЕ теку, яку створив він сам (`WORKTREE_CREATED`), а
#     теку, створену не ним, він не чіпає й каже це. `--release` теж питає диск
#     після `worktree remove` — там повідомлення «копію прибрано» було з того
#     самого коду виходу. Два повідомлення того самого класу лишаються, і вони
#     названі, а не замовчані: `worktree prune` («застарілий запис копії
#     прибрано», вітка «теки не було») і `rmdir` порожньої незареєстрованої теки
#     («порожню незареєстровану теку прибрано») у `--release`. Обидва спираються
#     на код виходу, але жодне не обіцяє, що прибрано КОПІЮ, — тож цим тікетом
#     вони не закриті;
#   * факти збираються з КОПІЇ (вона ж і є свіжий `origin/main`), а не з тієї
#     робочої копії, з якої скрипт запущено: саме так число належить базі
#     смуги, а не дереву координатора, яке могло відстати. Це саме тому й
#     премиса тікета питається з КОПІЇ: версія механізму мусить бути тією, з
#     якою смуга працюватиме;
#   * знахідка премиси (код 1) і невідомість її вердикту (код 2 механізму) —
#     ПОПЕРЕДЖЕННЯ, а не відмова: застарілий тікет — не привід не створювати
#     смугу, але привід не створювати її мовчки. Ціна вибору виміряна й
#     названа в кроці нижче, разом із межею «код 2 від смуги — лише коли
#     перевірити не вдалося взагалі»; галасливий гейт обходять, і це та сама
#     межа, що в решті кроків;
#   * числа `--scan 200` у кроці премиси (база 424655b1) пінить ГЕЙТ — через
#     ЗАПИС `SCAN_WINDOW` у `issue_premise.py` (#1328), як `PRICES`: у гейта
#     немає ні `gh`, ні мережі, тож джерелом стає запис, а не прогін. Файл `.sh`
#     гейт тепер бачить (`SCANNED`, #1328: усі 20 верхньорівневих кроків, прогін
#     на незміненому дереві дав 0 знахідок), і числа стоять у кроці по одному на
#     рядок — так їх читає джерело `record`; зіпсоване число — знахідка. Межа
#     запису названа там-таки: це ЗНІМОК рухомого вікна, його оновлює руками
#     той, хто переміряв `--scan 200`. Це саме названо й біля самих чисел, у
#     кроці нижче;
#
# Коди виходу:
#   0 — смугу створено (або копію прибрано);
#   1 — відмова: у копії є що втрачати (незакомічені зміни, незавершена
#       операція) — тільки `--release`;
#   2 — перевірити не вдалося АБО смуга зайнята: невідомий аргумент, немає
#       `git`/мережі, копія вже існує, тікет зарезервовано, база не прочитана,
#       факти не зібрано, ПРЕМИСУ ТІКЕТА НЕ ПРОЧИТАНО (issue_premise.py не дав
#       вердикту — `gh` не відповів, тікет не читається), `local.properties` є,
#       але перенести його не вдалося, `--plan` назвав шлях, якого немає в
#       `origin/main` (#1337), або не ФАЙЛ, а теку/дерево (#1340), або механізм
#       віддав
#       код, якого його контракт не знає. Копія при цьому НЕ створюється: якщо
#       її встигли створити, її прибирає той самий прогін (відкат — лише те, що
#       створив він сам). Знахідка премиси (код 1) і невідомість її вердикту
#       (код 2 механізму) сюди НЕ входять: це попередження у фактах, і смуга
#       лишається — чому саме так, названо в кроці премиси нижче.
#
# Змінні (ті самі, що в тестах):
#   NEW_LANE_REPO / NEW_LANE_GIT / NEW_LANE_PYTHON / NEW_LANE_OWNER /
#   NEW_LANE_RESERVATION / NEW_LANE_PLAN
set -euo pipefail

GIT="${NEW_LANE_GIT:-git}"
PYTHON="${NEW_LANE_PYTHON:-python3}"
# Абсолютна тека самого скрипта: нею резервування кличеться з будь-якого cwd
# (нижче ми заходимо в `$REPO`), і `NEW_LANE_REPO` може вказувати на ІНШУ копію,
# у якій `agent-work-claim.py` може бути старішим або його не бути зовсім.
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

# Тека смуг у робочій копії — константа, а не здогад: за нею копію знаходять і
# створення, і `--release`, і саме її названо в брифі.
LANES_DIR=".worktrees"

usage() {
  printf 'usage: scripts/new-lane.sh <номер> <slug> [--owner <id>] [--reservation <назва>] [--plan <наявний-шлях>]\n'
  printf '       scripts/new-lane.sh --release <номер>\n'
  printf '\n'
  printf 'Резервує тікет, створює копію смуги від свіжого origin/main і друкує факти для брифа.\n'
  printf 'Премису тікета перевіряє issue_premise.py: застарілий тікет названо у фактах, смуга лишається.\n'
  printf -- '--release прибирає копію, коли в ній немає незакомічених змін (гілку не видаляє).\n'
  printf 'Власник резервування: --owner, або NEW_LANE_OWNER, або DSH_SESSION_ID.\n'
  printf -- '--plan бере лише наявний в origin/main ФАЙЛ (blob); тека (tree) — відмова, а без --plan у записі буде null.\n'
  printf 'Коди виходу: 0 — створено (прибрано); 1 — у копії є що втрачати; 2 — відмова/невідомість.\n'
}

fail() {
  printf 'FAIL  new-lane: %s\n' "$*" >&2
  exit 2
}

refuse() {
  printf 'FAIL  new-lane: %s\n' "$*" >&2
  exit 1
}

# --------------------------------------------------------------------------
# Аргументи
# --------------------------------------------------------------------------

ISSUE=""
SLUG=""
RELEASE=false
OWNER_FLAG=""
RESERVATION_FLAG=""
PLAN_FLAG=""

while [ "$#" -gt 0 ]; do
  case "$1" in
    -h | --help) usage; exit 0 ;;
    --release) RELEASE=true; shift ;;
    --owner)
      OWNER_FLAG="${2:-}"
      [ -n "$OWNER_FLAG" ] || fail "--owner потребує значення"
      shift 2
      ;;
    --reservation)
      RESERVATION_FLAG="${2:-}"
      [ -n "$RESERVATION_FLAG" ] || fail "--reservation потребує значення"
      shift 2
      ;;
    --plan)
      PLAN_FLAG="${2:-}"
      [ -n "$PLAN_FLAG" ] || fail "--plan потребує значення"
      shift 2
      ;;
    -*)
      fail "невідомий прапорець: $1 (спробуй --help)"
      ;;
    *)
      if [ -z "$ISSUE" ]; then
        ISSUE="$1"
      elif [ -z "$SLUG" ]; then
        SLUG="$1"
      else
        fail "зайвий аргумент: $1"
      fi
      shift
      ;;
  esac
done

case "$ISSUE" in
  '') fail "не названо номер тікета (спробуй --help)" ;;
  *[!0-9]*) fail "номер тікета мусить бути числом: $ISSUE" ;;
esac
if [ "$ISSUE" -le 0 ]; then
  fail "номер тікета мусить бути додатним: $ISSUE"
fi

if [ "$RELEASE" = true ] && [ -n "$SLUG" ]; then
  fail "--release не бере slug: він знаходить копію за номером ($SLUG зайвий)"
fi
if [ "$RELEASE" = false ]; then
  case "$SLUG" in
    '') fail "не названо slug смуги (спробуй --help)" ;;
    *[!a-z0-9-]*) fail "slug дозволяє лише [a-z0-9-]: $SLUG" ;;
    *[a-z0-9]*) ;;
    *) fail "slug мусить мати принаймні одну літеру чи цифру: $SLUG" ;;
  esac
fi

