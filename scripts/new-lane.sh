REPO="${NEW_LANE_REPO:-}"
if [ -z "$REPO" ]; then
  REPO="$("$GIT" rev-parse --show-toplevel)" ||
    fail "не вдалося знайти корінь робочої копії (немає git?)"
fi
REPO="$(cd "$REPO" 2>/dev/null && pwd)" ||
  fail "робоча копія не знайдена: ${NEW_LANE_REPO:-$REPO}"
if [ ! -d "$REPO/.git" ] && [ ! -f "$REPO/.git" ]; then
  fail "$REPO не є робочою копією git (немає .git)"
fi

LANE="$REPO/$LANES_DIR/w$ISSUE"
BRANCH="t$ISSUE-$SLUG"

# Джерело `local.properties` — корінь робочої копії, і тільки він: там його
# тримає ручний рецепт (`docs/agents/local-environment.md`), звідти його
# копіювали руками для #1187, і жодного іншого місця скрипт не вигадує.
LOCAL_PROPERTIES="$REPO/local.properties"

# Запис worktree Є — будь-який, і живий, і застарілий (`prunable`).
worktree_recorded() {
  # Абсолютні шляхи: `git worktree list --porcelain` друкує рівно їх.
  "$GIT" -C "$REPO" worktree list --porcelain 2>/dev/null |
    grep -Fxq "worktree $1"
}

# Запис worktree ЖИВИЙ: він Є й git НЕ позначив його `prunable`. Різниця не
# косметична: застарілий запис (теку прибрали out-of-band, а `.git/worktrees/<id>`
# лишився) друкує `prunable …`, і якщо вважати його зареєстрованим, то
# `git -C "$LANE"` у теці на тому ж шляху піднімається до БАТЬКІВСЬКОГО
# репозиторію — тобто симптом F1 повертається разом із глухим кутом.
worktree_live() {
  "$GIT" -C "$REPO" worktree list --porcelain 2>/dev/null | awk -v lane="$1" '
    /^worktree / { path = substr($0, 10); stale = 0; next }
    /^prunable/  { if (path == lane) stale = 1; next }
    /^$/         { if (path == lane && !stale) { print "yes"; exit } path = ""; next }
    END          { if (path == lane && !stale) print "yes" }
  ' | grep -qx yes
}

# Шлях — СПРАВЖНІЙ чекаут смуги, а не тека всередині батьківського репозиторію:
# `--show-toplevel` у ній дорівнює їй самій. Це друга, незалежна від запису
# перевірка — і єдина, що стоїть між `git -C "$LANE"` і деревом координатора.
lane_is_checkout() {
  [ -d "$1" ] || return 1
  [ "$("$GIT" -C "$1" rev-parse --show-toplevel 2>/dev/null)" = "$(cd "$1" && pwd -P)" ]
}

COMMON="$("$GIT" -C "$REPO" rev-parse --path-format=absolute --git-common-dir)" ||
  fail "не вдалося прочитати спільний git-каталог"
CLAIM_FILE="$COMMON/agent-work-claims/$ISSUE.json"

# --------------------------------------------------------------------------
# Відкат: прибираємо ЛИШЕ те, що створив цей самий прогін
# --------------------------------------------------------------------------

WORKTREE_CREATED=false
CLAIM_CREATED=false

# Чи це НАШ запис резервування — порівнюється РОЗІБРАНИЙ JSON, а не рядок файлу
# (#1340). Рядкове порівняння (`grep -Fq "\"reservation\": \"$RESERVATION\""`)
# не бачило назви з лапкою: `json.dump` екранує її як `\"`, рядок не збігається —
# і файл лишався на диску, хоч відкат казав «резервування прибрано». Значення
# поля не залежить від екранування, тож назва з лапкою прибирається так само, як
# звичайна. Нерозібраний або чужий запис своїм не вважається — примусового
# звільнення в механізмі немає.
claim_is_ours() {
  "$PYTHON" -c '
import json, sys
try:
    with open(sys.argv[1], encoding="utf-8") as handle:
        claim = json.load(handle)
except (OSError, ValueError):
    sys.exit(1)
sys.exit(0 if claim.get("reservation") == sys.argv[2] else 1)
' "$CLAIM_FILE" "$RESERVATION"
}

# Факт про резервування ставить САМ відкат, і ставить його ПІСЛЯ спроби
# прибирання: повідомлення мусить називати те, що лишилося на диску, а не те,
# що відкат мав намір зробити (#1340). Кожне місце, яке кличе `rollback`,
# вставляє цей факт у своє повідомлення — тож «прибрано» звучить лише тоді,
# коли файлу справді немає.
ROLLBACK_CLAIM_FACT="резервування не створювалося"

# Чи лишився шлях на диску. `-e` не бачить посилання, яке нікуди не веде, а воно
# теж слід; тож питаються обидві форми. Це стан ДИСКА — і саме він, а не код
# виходу команди, дає факт нижче.
lane_present() {
  [ -e "$1" ] || [ -L "$1" ]
}

# Факт про КОПІЮ ставить сам відкат, і ставить його ТИМ САМИМ способом, що й
# факт про резервування (#1343). Код виходу `git worktree remove` каже, що
# команда мала намір зробити, а не що лишилося: відмова (права, чужий процес,
# підмінений `git`) і навіть успішний вихід із текою на диску лишали
# повідомлення «копію прибрано» без копії за ним. Тому після спроби питається
# ДИСК, і кожне місце, яке кличе `rollback`, вставляє цей факт у своє
# повідомлення — поряд із фактом про резервування.
ROLLBACK_LANE_FACT="копії не створювалося"

rollback() {
  local lane_remove_failed=false lane_remove_error=""
  if [ "$WORKTREE_CREATED" = true ]; then
    # `--force` тут законний рівно тому, що копію створив ЦЕЙ прогін: перед
    # `worktree add` перевірено, що ні теки, ні реєстрації не було, тож
    # видаляти нічиє. (Факти збираються в копії, і перший же прогін
    # `guard_witnesses.py --count` лишає в ній `__pycache__`: у цьому
    # репозиторії він ігнорований, а в чужому дереві міг би й не бути — і тоді
    # `remove` без `--force` відмовив би, лишивши по собі саме ту напівкопію,
    # яку відкат і прибирає.) Вивід `remove` не викидається: коли тека лишиться,
    # саме він і стане НАЗВАНОЮ причиною. `prune` лишається запасним ходом на
    # відмову `remove` (застарілий запис без теки прибирає він), але вердикт
    # ставить не він.
    if ! lane_remove_error="$("$GIT" -C "$REPO" worktree remove --force "$LANE" 2>&1)"; then
      lane_remove_failed=true
      "$GIT" -C "$REPO" worktree prune 2>/dev/null || true
    fi
  fi
  # Причина йде в повідомлення одним рядком — факти вставляються, а не
  # друкуються блоком.
  lane_remove_error="${lane_remove_error//$'\n'/ }"
  if lane_present "$LANE"; then
    if [ "$WORKTREE_CREATED" != true ]; then
      ROLLBACK_LANE_FACT="копія ЛИШИЛАСЯ: $LANE — цей відкат її не прибирав (копію створив не він: git worktree add не вдався); прибери її руками"
    elif [ "$lane_remove_failed" = true ]; then
      ROLLBACK_LANE_FACT="копія ЛИШИЛАСЯ: $LANE — git worktree remove відмовив (${lane_remove_error:-без повідомлення}); прибери її руками: $GIT -C $REPO worktree remove --force $LANE"
    else
      ROLLBACK_LANE_FACT="копія ЛИШИЛАСЯ: $LANE — git worktree remove вийшов без помилки, але тека лишилася на диску; прибери її руками: $GIT -C $REPO worktree remove --force $LANE"
    fi
  elif [ "$WORKTREE_CREATED" = true ]; then
    ROLLBACK_LANE_FACT="копію прибрано"
  else
    ROLLBACK_LANE_FACT="копії немає — цей прогін її не створював"
  fi
  if [ "$CLAIM_CREATED" = true ]; then
    # Прибираємо рівно той запис, який створили самі: чужий запис із тим самим
    # номером неможливий (acquire атомарний), але перевірка лишається — інакше
    # відкат був би примусовим звільненням, якого в механізмі немає.
    if [ -f "$CLAIM_FILE" ] && claim_is_ours; then
      # Збій `rm` тут не сміє валити відкат кодом 1 («у копії є що втрачати»):
      # справжній стан назве перевірка нижче.
      rm -f -- "$CLAIM_FILE" 2>/dev/null || true
    fi
    if [ -f "$CLAIM_FILE" ]; then
      ROLLBACK_CLAIM_FACT="резервування ЛИШИЛОСЯ: $CLAIM_FILE — воно не наше (чуже або нерозібране) чи його не вдалося прибрати; зніми його руками, якщо це справді наше"
    else
      ROLLBACK_CLAIM_FACT="резервування прибрано"
    fi
  fi
}

# --------------------------------------------------------------------------
# --release: прибрати копію, коли в ній нема чого втрачати
# --------------------------------------------------------------------------

if [ "$RELEASE" = true ]; then
  if [ ! -e "$LANE" ] && ! worktree_recorded "$LANE"; then
    fail "немає смуги w$ISSUE у $REPO — нема чого звільняти"
  fi
  LANE_BRANCH=""
  if worktree_live "$LANE" && lane_is_checkout "$LANE"; then
    # ЖИВИЙ чекаут смуги — і ТІЛЬКИ тут `git -C "$LANE"` читає саму копію.
    LANE_BRANCH="$("$GIT" -C "$LANE" rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
    DIRTY="$("$GIT" -C "$LANE" status --porcelain)" ||
      fail "не вдалося прочитати стан копії $LANE"
    if [ -n "$DIRTY" ]; then
      printf 'FAIL  копія %s має незакомічені зміни — прибирання втратило б їх:\n' "$LANE" >&2
      printf '%s\n' "$DIRTY" | sed 's/^/      /' >&2
      refuse "закоміть або збережи їх, тоді повтори scripts/new-lane.sh --release $ISSUE"
    fi
    for marker in rebase-merge rebase-apply MERGE_HEAD; do
      if [ -e "$("$GIT" -C "$LANE" rev-parse --git-path "$marker")" ]; then
        refuse "копія $LANE посеред операції ($marker) — заверши або скасуй її, тоді повтори"
      fi
    done
    if ! "$GIT" -C "$REPO" worktree remove "$LANE"; then
      fail "git worktree remove не прибрав $LANE"
    fi
    # «Прибрано» тут — теж факт про ДИСК, а не про код виходу (#1343): та сама
    # межа, що в `rollback`. `worktree remove` може вийти нулем і лишити теку —
    # і «OK копію прибрано» було б обіцянкою без копії за нею.
    if lane_present "$LANE"; then
      fail "git worktree remove вийшов без помилки, але тека $LANE лишилася на диску — прибери її руками: $GIT -C $REPO worktree remove --force $LANE"
    fi
    printf 'OK    копію прибрано: %s\n' "$LANE"
  elif [ -e "$LANE" ]; then
    # Шлях Є, але чекаутом смуги НЕ є: незареєстрована тека або ЗАСТАРІЛИЙ
    # (prunable) запис, чия тека зникла й була створена знову як звичайна.
    # `git -C "$LANE"` тут піднявся б до БАТЬКІВСЬКОГО репозиторію й прочитав
    # дерево КООРДИНАТОРА — і тоді «копія має зміни» назвало б чужі зміни, а
    # номер лишився б заблокованим назавжди: створити — відмова, а підказане
    # лікування не працює. Тому тут ми НЕ кличемо git у цій теці взагалі.
    if worktree_live "$LANE"; then
      # Живий запис, але не чекаут: стан, якого ми не розуміємо, — не чіпаємо.
      refuse "шлях $LANE має живий worktree-запис, але не є чекаутом смуги — стан невідомий; розбери його руками"
    fi
    # Застарілий запис більше ні на що не вказує: прибираємо його (живих prune
    # не чіпає), щоб той самий номер не лишався зайнятим привидом.
    if ! "$GIT" -C "$REPO" worktree prune; then
      fail "не вдалося прибрати застарілий запис копії $LANE"
    fi
    if [ -d "$LANE" ] && [ -z "$(ls -A "$LANE")" ]; then
      if ! rmdir "$LANE"; then
        fail "порожню незареєстровану теку $LANE не прибрано"
      fi
      printf 'OK    порожню незареєстровану теку прибрано: %s (чекаутом смуги вона не була)\n' "$LANE"
    elif [ -d "$LANE" ]; then
      refuse "шлях $LANE не є чекаутом смуги, але тека не порожня — прибирання втратило б її вміст ($(ls -A "$LANE" | tr '\n' ' ')); прибери її руками, якщо впевнений"
    else
      # Не тека, а щось інше (файл, посилання): вмісту «списком» тут немає, і
      # вигадувати його не треба — просто не чіпаємо.
      refuse "шлях $LANE не є чекаутом смуги і не є текою (файл чи посилання) — прибирання втратило б його; прибери його руками, якщо впевнений"
    fi
  else
    # Теки немає, а запис є — застарілий. Прибираємо запис, а не вдаємо, що
    # смуги не було: інакше він лишився б привидом, на який впав би `worktree add`.
    if ! "$GIT" -C "$REPO" worktree prune; then
      fail "не вдалося прибрати застарілий запис копії $LANE"
    fi
    printf 'OK    застарілий запис копії прибрано (теки не було): %s\n' "$LANE"
  fi
  printf 'OK    гілку %s не видаляю: вона лишається в refs/heads (та сама межа, що в merge-pr.sh).\n' \
    "${LANE_BRANCH:-смуги}"
  if [ -f "$CLAIM_FILE" ]; then
    printf 'резервування лишається: %s\n' "$CLAIM_FILE"
    printf '      знімає його координатор — видали файл, коли тікет закрито.\n'
  fi
  exit 0
fi

# --------------------------------------------------------------------------
# Створення смуги
# --------------------------------------------------------------------------

# Свіжа база — ДО резервування: якщо мережі немає, тікет не лишається зайнятим.
if ! "$GIT" -C "$REPO" fetch origin main; then
  fail "не вдалося оновити origin/main (мережа?) — копії не створено, тікет не зарезервовано"
fi
if ! BASE="$("$GIT" -C "$REPO" rev-parse origin/main)"; then
  fail "не вдалося прочитати origin/main — копії не створено, тікет не зарезервовано"
fi
BASE_SHORT="$("$GIT" -C "$REPO" rev-parse --short origin/main)"

# Застарілі записи (тека зникла, `.git/worktrees/<id>` лишився) прибираємо ДО
# перевірки: інакше номер вважався б зайнятим записом-привидом, а `worktree add`
# упав би на «missing but already registered worktree». `prune` живих не чіпає.
if ! "$GIT" -C "$REPO" worktree prune; then
  fail "не вдалося прибрати застарілі записи worktree — копії не створено"
fi

# Копія зайнята — відмова ДО резервування: друга смуга в ту саму копію не сідає,
# і тікет не лишається зайнятим неіснуючою смугою.
if [ -e "$LANE" ] || worktree_recorded "$LANE"; then
  fail "копія вже існує: $LANE — друга смуга в ту саму копію не сідає. Прибери її (scripts/new-lane.sh --release $ISSUE) або візьми інший номер."
fi
if "$GIT" -C "$REPO" show-ref --verify --quiet "refs/heads/$BRANCH"; then
  fail "гілка $BRANCH вже існує — це залишок попередньої смуги (гілки цей репозиторій не видаляє). Візьми інший slug або прибери залишок руками, якщо він злитий."
fi

OWNER="${OWNER_FLAG:-${NEW_LANE_OWNER:-${DSH_SESSION_ID:-}}}"
if [ -z "$OWNER" ]; then
  fail "не названо власника резервування: дай --owner <thread-id>, NEW_LANE_OWNER або DSH_SESSION_ID"
fi
RESERVATION="${RESERVATION_FLAG:-${NEW_LANE_RESERVATION:-$SLUG}}"

# Поле `plan` (#1337). Типового шляху НЕМАЄ: скрипт більше не вигадує
# `docs/plans/<дата>-<номер>-<slug>.md` — плану на цей момент не існує, і запис,
# який на нього вказує, каже одне, а реальність — інше (`#1337`: жоден із
# записаних `docs/plans/…` не існував). Названий явно шлях перевіряється проти
# бази смуги ДО резервування: тоді в записі стоїть рівно те, що справді є, або
# `null`. Перевірка йде через `git cat-file -t origin/main:<шлях>` (а не по
# диску тієї копії, з якої запущено скрипт): база смуги — `origin/main`, і шлях
# мусить бути ФАЙЛОМ (`blob`) саме в ній, інакше запис знову розійшовся б із
# реальністю (#1337 — неіснуючий шлях, #1340 — тека, яку `-e` теж приймав).
PLAN="${PLAN_FLAG:-${NEW_LANE_PLAN:-}}"
if [ -n "$PLAN" ]; then
  # Тип питається (`-t`), а не лише існування (`-e`): дерево теж існує (#1340).
  # `git cat-file -e origin/main:docs` відповідає «так», і тека потрапляла в
  # запис як план — твердження поля («шлях існує») виконувалося, а сенс — ні.
  # Планом вважається ЛИШЕ blob (файл): tree/commit/tag — відмова з названим
  # типом, бо запис, який називає теку планом, знову каже одне, а реальність —
  # інше. Неіснуючий шлях — та сама відмова, що й до #1340 (#1337).
  PLAN_OBJECT="$("$GIT" -C "$REPO" cat-file -t "origin/main:$PLAN" 2>/dev/null || true)"
  case "$PLAN_OBJECT" in
    blob) ;;
    '')
      fail "план '$PLAN' не існує в origin/main — запис у резервуванні назвав би неіснуючий файл (#1337). Назви наявний шлях або не давай --plan: тоді в записі буде null"
      ;;
    tree)
      fail "план '$PLAN' — дерево (tree), а не файл плану: шлях існує, але тека планом не є (#1340). Назви ФАЙЛ (blob) або не давай --plan: тоді в записі буде null"
      ;;
    *)
      fail "план '$PLAN' — це $PLAN_OBJECT, а не файл плану: об'єкт такого типу планом не є (#1340). Назви ФАЙЛ (blob) або не давай --plan: тоді в записі буде null"
      ;;
  esac
  PLAN_FACT="план: $PLAN (є в origin/main)"
else
  PLAN_FACT="план: не задано (у резервуванні — null: плану смуги ще немає, і шлях не вигадується — #1337)"
fi

# Резервування — наявним механізмом, із його власним кодом виходу 2 на зайнятий
# тікет. Копії тут ще немає, тож «зайнято» не лишає по собі нічого. `--plan`
# передається ЛИШЕ коли шлях перевірено вище; без нього механізм пише `null`
# (саме тому `--plan` у нього необов'язковий — #1337).
set +e
CLAIM_ARGS=(acquire "$ISSUE" --owner "$OWNER" --reservation "$RESERVATION")
if [ -n "$PLAN" ]; then
  CLAIM_ARGS+=(--plan "$PLAN")
fi
CLAIM_OUT="$(
  cd "$REPO" &&
    "$PYTHON" "$SCRIPT_DIR/agent-work-claim.py" "${CLAIM_ARGS[@]}" 2>&1
)"
CLAIM_CODE=$?
set -e
if [ "$CLAIM_CODE" -ne 0 ]; then
  printf '%s\n' "$CLAIM_OUT" >&2
  fail "тікет #$ISSUE уже зарезервовано — копії не створено (код $CLAIM_CODE від agent-work-claim.py)"
fi
CLAIM_CREATED=true

if ! "$GIT" -C "$REPO" worktree add --detach "$LANE" origin/main; then
  rollback
  fail "git worktree add не вдався — смугу не зареєстровано; $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT"
fi
WORKTREE_CREATED=true

# --------------------------------------------------------------------------
# `local.properties`: крок ручного рецепта, який загубився при автоматизації
# (#1332)
# --------------------------------------------------------------------------
#
# Файл у `.gitignore` (`.gitignore:19`), тож у копію сам не потрапляє — а
# Android-збірка без нього падає `SDK location not found` і з'їдає прогін
# (так було в смуги #1187). Джерело названо одне: `$REPO/local.properties`.
# Немає файлу — не відмова, а НАЗВАНА причина, чому збірка в цій копії не
# працюватиме; факти нижче друкують і перше, і друге.
if [ -f "$LOCAL_PROPERTIES" ]; then
  if ! cp -- "$LOCAL_PROPERTIES" "$LANE/local.properties"; then
    rollback
    fail "local.properties є в $LOCAL_PROPERTIES, але перенести його в копію не вдалося — $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT"
  fi
  LOCAL_PROPERTIES_FACT="є — перенесено в копію з $LOCAL_PROPERTIES"
else
  LOCAL_PROPERTIES_FACT="НЕМА ($LOCAL_PROPERTIES) — Android-збірка в цій копії не працюватиме: Gradle не знайде SDK (SDK location not found), бо файл зі шляхом sdk.dir лежить у .gitignore і в копію не потрапляє. Поклади його в корінь робочої копії й перенеси вручну: cp local.properties $LANE/local.properties"
fi

# --------------------------------------------------------------------------
# Премиса тікета: застарілий тікет ловиться ДО роботи, а не після неї (#1324)
# --------------------------------------------------------------------------
#
# Навіщо саме тут. Тікет #1315 застарів МІЖ написанням і створенням смуги:
# `empty_shape_mutants.py --list` у ньому був 1, а став 2 (другий вхід прийшов
# із #1322, поки тікет лежав), і «`guard_witnesses` у main — 40» на базі було
# 56. Це третій різновид хибного числа — «число, яке БУЛО правдою»: перші два
# («з пам'яті» і «з припущення») закриває цей же скрипт, а третій народжується в
# ПРОЦЕСІ між тікетом і смугою, і жоден гейт у дереві його не бачить — усі вони
# дивляться на КОД. Смуга знайшла розходження сама, але вже працюючи.
#
# Механізм для цього існує від #1281 (`scripts/issue_premise.py`) — і його не
# кликав жоден крок. Це ВДРУГЕ, коли наявний механізм не викликають (першим був
# `agent-work-claim.py`, і його закрив цей самий скрипт, вставивши в крок, який
# координатор уже робить). Тому премиса стає таким самим кроком, а не правилом
# в інструкції: правило, яке треба пам'ятати, — не правило.
#
# Межі цього кроку — тут, у коді, а не лише у звіті:
#   * перевірка йде з КОПІЇ (та сама межа, що в решті фактів): дерево
#     координатора могло відстати, а версія механізму мусить бути тією, з якою
#     смуга працюватиме;
#   * знахідка (код 1: шлях із тіла зник з `origin/main`, або позначений `NEW:`
#     там уже є) — ПОПЕРЕДЖЕННЯ зі збереженням смуги, а не відмова. Це вибір, і
#     він виміряний: застарілий тікет — не привід не створювати смугу (копія
#     дешева й оборотна, а переписування тікета — ні), але привід НЕ створювати
#     її мовчки. Ціна відмови названа командою на базі 424655b1
#     (`python3 scripts/issue_premise.py --scan 200`), і числа стоять ПО ОДНОМУ
#     на рядок — так їх читає джерело `record` у `doc_numbers.py`:
#       «премиса є» — 102
#       «у тілі немає шляхів у бектиках» — 78
#       «ім'я неоднозначне» — 11
#       «відмов» — 9
#     Відмова на цих 9 заблокувала б справжню роботу, бо три з них — документовані
#     хибні відмови механізму (#962, #1029, #822: локальний звіт, ім'я фікстури
#     й проза з крапкою). ЦІ ЧОТИРИ ЧИСЛА ПІНИТЬ ГЕЙТ — через ЗАПИС `SCAN_WINDOW`
#     у `issue_premise.py` (#1328), як `PRICES`, а не через прогін: у гейта
#     немає ні `gh`, ні мережі, тож зіпсоване число — знахідка, а не тиша. Межа
#     запису названа там-таки: це ЗНІМОК рухомого вікна, його оновлює руками
#     той, хто переміряв `--scan 200` (на `584dda73` те саме вікно дає
#     104/77/11/8). Пінить їх запис і ревізія `424655b1`, і оновлює його той
#     самий прогін, який їх міряє;
#   * НЕВІДОМІСТЬ ВЕРДИКТУ (код 2 механізму: шляхів у бектиках немає АБО ім'я
#     неоднозначне) — теж попередження, але з НАЗВАНИМ словом «невідомість»:
#     «нічого не перевірено» не дорівнює «все гаразд», і саме це друкується.
#     Відмова тут коштувала б 89 смуг із тих самих 200 (78 + 11) і зробила б
#     крок галасливим — а галасливий гейт обходять;
#   * код 2 ВІД СМУГИ лишається за станом, коли механізм НЕ УВІКЛЮЧИВСЯ: тікет
#     не прочитано (`gh` не відповів, тікет не читається) або вердикту немає
#     взагалі. Тоді перевірити не вдалося, і це видно: копії, резервування й
#     гілки не лишається;
#   * код, якого контракт механізму не знає, — теж код 2: невідомий вердикт не
#     можна прочитати на свою користь;
#   * `--release` премису не перевіряє: прибирання копії не про тікет;
#   * МЕЖА КЛАСУ, і вона названа прямо: перевіряються ШЛЯХИ, а не твердження
#     тікета. Приклад, з якого цей тікет народився, механізм НЕ ловить:
#     `python3 scripts/issue_premise.py --quiet --issue 1315` і сьогодні дає
#     «ПРЕМИСА Є» — застарілі числа з #1315 (`empty_shape_mutants --list` 1 → 2,
#     «`guard_witnesses` у main — 40» → 56; третє було в тексті цілі, не тікета)
#     лежать у ПРОЗІ, а не в шляхах. Отже крок закриває застарілу ШЛЯХ-премису
#     (шлях зник із `origin/main`, або `NEW:` стоїть на тому, що вже є), а не
#     будь-яке число в тілі. Числа в прозі лишаються незакритими — і це сказано
#     тут, щоб крок не вдавав повноти;
#   * ціна кроку — один виклик `gh` і кілька `git`-питань у копії: виміряно
#     `0.65 с` на тікеті #1324, і це менше за `git fetch`, який скрипт робить і
#     без нього. Крок прийнятний саме тому, що ціна названа числом, а не
#     обіцянкою;
#   * у кроку немає вимикача: вимкнена перевірка — це перевірка, якої немає.

set +e
PREMISE_REPORT="$(cd "$LANE" && "$PYTHON" scripts/issue_premise.py --quiet --issue "$ISSUE")"
PREMISE_CODE=$?
set -e

# Вердикт є ⇒ у stdout є рядок (навіть `--quiet` друкує підсумок); вердикту
# немає ⇒ stdout порожній, а причина — у stderr механізму, і він ллється просто
# в stderr цього скрипта, тож помилка `gh` видна без переказу й без здогаду.
# Це єдиний сигнал, який механізм дає між цими станами, і він названий тут, а не
# вгаданий.
if [ -z "$PREMISE_REPORT" ]; then
  rollback
  fail "тікет #$ISSUE не прочитано: issue_premise.py не дав вердикту (gh не відповів?) — премису перевірити не вдалося; $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT; гілку $BRANCH цей прогін не створював (її створює останній крок)"
fi

case "$PREMISE_CODE" in
  0) PREMISE_FACT="ПРЕМИСА Є — шляхи, названі в тілі, є в origin/main" ;;
  1) PREMISE_FACT="ВІДМОВА (код 1) — тікет застарів або шлях названо неточно; смугу створено, але подивись це ДО роботи" ;;
  2) PREMISE_FACT="НЕВІДОМІСТЬ (код 2) — перевірити не вдалося; смугу створено, і «все гаразд» тут не сказано" ;;
  *)
    rollback
    fail "issue_premise.py віддав код $PREMISE_CODE, якого контракт не знає — вердикт незрозумілий; $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT; гілку $BRANCH цей прогін не створював (її створює останній крок)"
    ;;
esac

# Факти — з КОПІЇ: вона і є свіжий origin/main. Джерел три, і кожне мусить
# відповісти; інакше це невідомість (2), а не бриф із вигаданим числом.
if ! WITNESSES="$(cd "$LANE" && "$PYTHON" scripts/guard_witnesses.py --count)"; then
  rollback
  fail "не вдалося прочитати реєстр сторожів із копії (scripts/guard_witnesses.py --count) — $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT"
fi
case "$WITNESSES" in
  '' | *[!0-9]*)
    rollback
    fail "guard_witnesses.py --count віддав не число: '$WITNESSES' — $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT"
    ;;
esac

if ! JOB_LIST="$(cd "$LANE" && "$PYTHON" scripts/ci_job_time.py --list --root "$LANE")"; then
  rollback
  fail "не вдалося прочитати ліміт джоби з копії (scripts/ci_job_time.py --list) — $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT"
fi
JOB_NAME="$(printf '%s\n' "$JOB_LIST" | sed -n 's/^джоба: \([^ ]*\).*/\1/p')"
JOB_LIMIT="$(printf '%s\n' "$JOB_LIST" | sed -n 's/^ліміт: //p')"
if [ -z "$JOB_NAME" ] || [ -z "$JOB_LIMIT" ] || [ "${JOB_LIMIT#НЕВІДОМО}" != "$JOB_LIMIT" ]; then
  rollback
  fail "ліміт джоби не прочитано з копії ('$JOB_NAME' / '$JOB_LIMIT') — $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT"
fi

# Гілку смуги створюємо ОСТАННІМ кроком, коли все вже перевірено: якщо факти не
# зібралися, відкат прибирає саму копію, і жодної гілки по собі не лишається —
# інакше наступна спроба вперлася б у «гілка вже існує» від власного невдалого
# прогону. `--no-track`: гілка смуги не «відстежує» origin/main, бо тоді
# `git status` бреше про базу — та сама хибна база, тільки тихіша.
if ! "$GIT" -C "$LANE" switch -q --no-track -c "$BRANCH"; then
  rollback
  fail "не вдалося створити гілку $BRANCH у копії — $ROLLBACK_LANE_FACT; $ROLLBACK_CLAIM_FACT"
fi

# --------------------------------------------------------------------------
# Факти для брифа: їх вставляють, а не згадують
# --------------------------------------------------------------------------

# Команди, які смуга проганяє САМА. Мердж сюди не входить: його запускає
# координатор, і він названий окремим рядком.
LANE_COMMANDS=(
  'python3 scripts/guard_witnesses.py'
  'python3 scripts/ci_job_time.py --check-docs'
  'python3 scripts/doc_numbers.py'
  'python3 scripts/named_boundaries.py'
  'python3 scripts/declared_fields.py'
  'python3 -m unittest discover -s scripts/tests -p "test_*.py"'
  'scripts/test-changed.sh'
)

printf 'смуга: %s\n' "$BRANCH"
printf 'копія: %s\n' "$LANE"
printf 'база: %s (%s, origin/main)\n' "$BASE_SHORT" "$BASE"
printf 'резервування: %s (owner: %s, %s)\n' "$CLAIM_FILE" "$OWNER" "$RESERVATION"
printf 'премиса тікета: %s\n' "$PREMISE_FACT"
if [ "$PREMISE_CODE" -ne 0 ]; then
  # Знахідка й невідомість вердикту названі ПОВНІСТЮ — тими самими рядками, які
  # надрукував механізм (`--quiet` мовчить про зелені шляхи й називає решту).
  # Переказ тут був би другим місцем істини; це та сама межа, що в решті фактів.
  printf '%s\n' "$PREMISE_REPORT" | sed 's/^/      /'
fi
printf 'сторожів у реєстрі: %s\n' "$WITNESSES"
printf 'ліміт джоби %s: %s\n' "$JOB_NAME" "$JOB_LIMIT"
printf 'local.properties: %s\n' "$LOCAL_PROPERTIES_FACT"
printf '%s\n' "$PLAN_FACT"
printf 'команди смуги (прогнати самій):\n'
for command in "${LANE_COMMANDS[@]}"; do
  printf '  %s\n' "$command"
done
printf 'мердж: scripts/merge-pr.sh <номер PR> — зливає координатор, не `gh pr merge`\n'
printf 'звільнити копію після мерджу: scripts/new-lane.sh --release %s\n' "$ISSUE"
