#!/usr/bin/env python3
"""Export public Ukrainian catalogue metadata into the worker's input format.

Walks the supported, non-scam sources' own sitemaps and JSON catalogue:

- chitaka.com.ua (9 book sitemaps)
- audiobook.co.ua (3 post sitemaps)
- chytaylo.com.ua (book URLs in the sitemap)
- sound-books.net (book posts in news_pages.xml)
- sluhay.com.ua (/find/allcards JSON)
- knigi-online.com.ua (book posts; non-book posts are skipped)

The title/author extraction follows the Android adapters' rules. Only public
catalogue facts and descriptions are written; no page HTML, audio URL, cookie
or listener field survives. The remainder up to --limit is filled from a
LibriVox catalogue (already generated by catalog_from_librivox.py).
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import html
import json
from pathlib import Path
import re
import time
from html.parser import HTMLParser
from urllib.parse import urlsplit

from public_catalog_http import CatalogSecurityError, fetch_text

from merge_key import merge_key

UA = {"User-Agent": "slukhayka-catalog/1"}
MAX_TEXT = 4000
SPACE = re.compile(r"\s+")
TAG = re.compile(r"<[^>]+>")
LD = re.compile(r'<script[^>]+type=["\']application/ld\+json["\'][^>]*>(.*?)</script>', re.S | re.I)


def fetch(url, timeout=25, headers=None):
    return fetch_text(url, timeout=timeout, headers=headers)


def fetch_json(url, headers=None):
    return json.loads(fetch(url, headers=headers))


def og(html_text, name):
    escaped = re.escape(name)
    for pattern in (
        r'<meta[^>]+(?:property|name)=["\']' + escaped + r'["\'][^>]+content=["\']([^"\']*)',
        r'<meta[^>]+content=["\']([^"\']*)["\'][^>]+(?:property|name)=["\']' + escaped + r'["\']',
    ):
        match = re.search(pattern, html_text, re.I)
        if match:
            return html.unescape(match.group(1)).strip()
    return ""


def jsonld(html_text):
    for block in LD.findall(html_text):
        try:
            yield json.loads(block)
        except Exception:
            continue


def clean(value):
    return SPACE.sub(" ", TAG.sub(" ", html.unescape(value or ""))).strip()


def name_of(value):
    if isinstance(value, dict):
        return str(value.get("name") or "").strip()
    if isinstance(value, list) and value:
        return name_of(value[0])
    return str(value or "").strip()


def text_of(title, author, description, language="uk"):
    body = clean(description)[:1200]
    base = ". ".join(part for part in (title.strip(), author.strip(), language) if part)
    return (f"{base}. {body}" if body else base)[:MAX_TEXT]


def sitemap(url):
    return re.findall(r"<loc>(.*?)</loc>", fetch(url))


def parse_soundbooks(html_text):
    for document in jsonld(html_text):
        entity = document.get("mainEntity") if isinstance(document, dict) else None
        if isinstance(entity, dict) and entity.get("@type") in ("Book", "Audiobook"):
            return name_of(entity.get("name")), name_of(entity.get("author")), entity.get("description", "")
        if isinstance(document, dict) and document.get("@type") in ("Book", "Audiobook"):
            return name_of(document.get("name")), name_of(document.get("author")), document.get("description", "")
    return "", "", ""


def parse_audiobookcoua(html_text):
    raw = og(html_text, "og:title").removeprefix("Аудиокнига ").strip()
    raw = re.sub(r"\s*-\s*Аудиокниги на украинском языке\s*$", "", raw)
    raw = re.sub(r"\s+скачать, слушать онлайн\s*$", "", raw).strip()
    if " - " in raw:
        title, author = raw.split(" - ", 1)
        return title.strip(), author.strip(), og(html_text, "og:description")
    return raw, "", og(html_text, "og:description")


class AudioClaim(HTMLParser):
    def __init__(self):
        super().__init__()
        self.in_audio = False
        self.playable = False

    def handle_starttag(self, tag, attrs):
        if tag == "audio":
            self.in_audio = True
        if self.in_audio and tag in ("audio", "source"):
            src = dict(attrs).get("src") or ""
            if urlsplit(src).path.lower().endswith(".mp3"):
                self.playable = True

    def handle_endtag(self, tag):
        if tag == "audio":
            self.in_audio = False


def has_audio(html_text):
    parser = AudioClaim()
    parser.feed(html_text)
    return parser.playable


def parse_chitaka(html_text):
    if not has_audio(html_text):
        return "", "", ""
    raw = og(html_text, "og:title")
    close = raw.find("»")
    if close < 0:
        return "", "", ""
    return raw[:close + 1].strip(), raw[close + 1:].split("⭐")[0].strip(), og(html_text, "og:description")


def parse_chytaylo(html_text):
    for document in jsonld(html_text):
        if isinstance(document, dict) and document.get("@type") == "Book":
            formats = document.get("bookFormat")
            if isinstance(formats, str):
                formats = [formats]
            # Chytaylo carries both audiobooks and ebooks on the same path;
            # only a declared AudiobookFormat is admissible.
            if not any(str(value).rstrip("/").rsplit("/", 1)[-1] == "AudiobookFormat"
                       for value in (formats or [])):
                continue
            return name_of(document.get("name")), name_of(document.get("author")), document.get("description", "")
    return "", "", ""


def parse_knigi(html_text):
    # The adapter's audio boundary is the AudioIgniter data-tracks-url block;
    # a page without it is a text book, not an audiobook.
    if not re.search(r'data-tracks-url="[^"]+"', html_text):
        return "", "", ""
    raw = og(html_text, "og:title").removeprefix("Аудіокнига ").strip()
    close = raw.find("»")
    if close < 0:
        return "", "", ""
    return raw[:close + 1].strip(), raw[close + 1:].strip(), og(html_text, "og:description")


def words(value):
    if isinstance(value, list):
        return [str(item).strip() for item in value if str(item).strip()]
    if isinstance(value, str):
        try:
            parsed = json.loads(value)
            if isinstance(parsed, list):
                return [str(item).strip() for item in parsed if str(item).strip()]
        except Exception:
            pass
        return [part.strip() for part in value.strip("[]").replace("'", "").split(",") if part.strip()]
    return []


def sample_page(url, parser):
    try:
        title, author, description = parser(fetch(url))
    except CatalogSecurityError:
        raise
    except Exception:
        return None
    if not title.strip() or not author.strip():
        return None
    return title, author, description, url


def add(works, title, author, description):
    key = merge_key(title, author)
    if key and key not in works:
        works[key] = text_of(title, author, description)
        return 1
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--limit", type=int, default=20_000)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--chitaka-limit", type=int, default=9000,
                        help="cap chitaka pages (it rate-limits a wide crawl); 0 skips it")
    parser.add_argument("--fill-librivox", type=Path,
                        help="LibriVox catalogue used only for the remainder up to --limit")
    args = parser.parse_args()
    works = {}
    counts = {}

    # 1. sluhay.com.ua: the API's own JSON, 30 cards per page.
    page = 1
    page_count = 1
    while page <= page_count and len(works) < args.limit:
        try:
            payload = fetch_json(f"https://sluhay.com.ua/find/allcards?search=&page={page}",
                                 headers={"x-requested-with": "XMLHttpRequest"})
        except CatalogSecurityError:
            raise
        except Exception:
            break
        page_count = int(payload.get("pageCount") or page)
        for card in payload.get("cards") or []:
            title = (card.get("bookName") or "").strip()
            authors = words(card.get("bookAuthor"))
            author = authors[0] if authors else ""
            counts["sluhayua"] = counts.get("sluhayua", 0) + add(
                works, title, author, card.get("text") or "")
            if len(works) >= args.limit:
                break
        page += 1

    # 2. HTML sources: sitemap URLs -> the adapter's own title/author rule.
    html_sources = []
    try:
        html_sources.append(("soundbooks", [
            url for url in sitemap("https://sound-books.net/news_pages.xml")
            if re.search(r"/\d+-[^/]+\.html$", url) and "/reklama/" not in url], parse_soundbooks))
    except CatalogSecurityError:
        raise
    except Exception:
        pass
    try:
        html_sources.append(("audiobookcoua", [
            url for m in ("https://audiobook.co.ua/post-sitemap.xml",
                          "https://audiobook.co.ua/post-sitemap2.xml",
                          "https://audiobook.co.ua/post-sitemap3.xml")
            for url in sitemap(m)], parse_audiobookcoua))
    except CatalogSecurityError:
        raise
    except Exception:
        pass
    try:
        html_sources.append(("chytaylo", [
            url for url in sitemap("https://chytaylo.com.ua/sitemap.xml") if "/books/" in url], parse_chytaylo))
    except CatalogSecurityError:
        raise
    except Exception:
        pass
    try:
        html_sources.append(("knigionline", sitemap("https://knigi-online.com.ua/post-sitemap.xml"), parse_knigi))
    except CatalogSecurityError:
        raise
    except Exception:
        pass
    if args.chitaka_limit:
        try:
            chitaka_maps = [url for url in sitemap("https://chitaka.com.ua/sitemap_index.xml")
                            if "/knigi-sitemap" in url]
            chitaka_urls = [url for m in chitaka_maps for url in sitemap(m)][:args.chitaka_limit]
            html_sources.append(("chitaka", chitaka_urls, parse_chitaka))
        except CatalogSecurityError:
            raise
        except Exception:
            pass

    for source, urls, page_parser in html_sources:
        if len(works) >= args.limit:
            break
        started = time.time()
        kept = 0
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            for index, row in enumerate(pool.map(lambda url: sample_page(url, page_parser), urls), 1):
                if row:
                    title, author, description, _ = row
                    kept += add(works, title, author, description)
                if index % 250 == 0:
                    print(json.dumps({"source": source, "seen": index, "kept": kept,
                                      "total": len(works), "seconds": round(time.time() - started, 1)}),
                          flush=True)
                if len(works) >= args.limit:
                    break
        counts[source] = kept

    ukrainian = len(works)

    # 3. Fill the remaining slots from the already-exported LibriVox catalogue.
    if len(works) < args.limit and args.fill_librivox and args.fill_librivox.is_file():
        for row in json.loads(args.fill_librivox.read_text()).get("works", []):
            if len(works) >= args.limit:
                break
            if row["workKey"] not in works:
                works[row["workKey"]] = row["text"]
        counts["librivox"] = len(works) - ukrainian

    payload = {"works": [{"workKey": key, "text": text} for key, text in sorted(works.items())]}
    args.output.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")))
    print(json.dumps({"works": len(works), "ukrainian": ukrainian, "sources": counts,
                      "bytes": args.output.stat().st_size, "output": str(args.output)}))


if __name__ == "__main__":
    main()
