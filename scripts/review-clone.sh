#!/usr/bin/env bash
#
# Одна команда для оглядача: копія на ПРАВИЛЬНІЙ ревізії й НАЗВАНА база дифу.
#
# Навіщо. Чотири огляди поспіль не змогли побудувати диф, і щоразу причина була
# не в незнанні, а в кроці, якого не існувало:
#
#   * #1320: `origin/main` застарів (і був shallow) — `git diff origin/main...HEAD`
#     упав на «no merge base», і базу довелося брати з `gh`;
#   * #1322: локальний `origin` був shallow — оглядач тягнув `--unshallow` руками;
#   * #1323: робоче дерево стояло на ІНШІЙ гілці — `git diff origin/main...HEAD`
#     дав чужий диф на 77 файлів;
#   * #1325: попередження в брифі («бери `origin/…`, не `HEAD`») не допомогло:
#     правило, яке треба пам'ятати, не правило.
#
# ЧЕСНО ПРО ПРИКЛАДИ. Shallow-половину цього списку на цій машині відтворити не
# вдалося, і це сказано, а не замовчано: ЖОДНА копія координатора не shallow —
# усі вони ділять один повний git-каталог (`git rev-parse
# --is-shallow-repository` = false, файлу `.git/shallow` немає), а в тілах і
# коментарях PR #1320–#1325 слова `shallow`/`unshallow` не згадані взагалі.
# Крок лишається, бо shallow — не вигадка, а стан, який дає будь-який
# `--depth`-клон (і свіжий CI-клон теж), і саме в ньому бази не існує, що
# доведено прогоном у `test_review_clone.ShallowTest`.
#
# Той самий крок уже є для смуги: `scripts/new-lane.sh` (#1321) бере свіжий
# `origin/main` і друкує факти ЗАМІСТЬ пам'яті. Тут — те саме для огляду:
# копія, взята з `origin/<гілка>`, і база, названа ПОВНИМ sha.
#
# Що робить:
#   1) прибирає застарілі записи worktree (`worktree prune`; живих не чіпає) і
#      відмовляє, якщо шлях копії вже зайнятий;
#   2) робить РІВНО ОДИН `git fetch origin` — два refspec'и, `origin/main` і
#      `refs/heads/<гілка>` (обидві до `refs/remotes/origin/…`), і `--unshallow`,
#      якщо репо shallow. Ні `git fetch origin` (усі гілки), ні теги сюди не
#      входять;
#   3) читає `origin/main` і `origin/<гілка>` — обидві саме з `origin`, не з
#      локальних гілок і не з `HEAD`;
#   4) рахує БАЗУ як `git merge-base origin/main origin/<гілка>` і питає
#      `--is-shallow-repository` ДО й ПІСЛЯ fetch'а: поки репо shallow,
#      merge-base може не знайтися або вийти заниженим, і мовчазна база тут
#      дорожча за відмову;
#   5) створює копію `git worktree add --detach <тека> <sha>` і друкує базу
#      повним sha, коротким sha, названу команду дифу, коміти попереду/позаду
#      й те, чи репо shallow і що з цим зроблено.
#
# Ціна кроку — названа числом, бо замовчана ціна стає сюрпризом. Обмін один:
# два refspec'и в одному `git fetch`. Виміряно на цій машині, коли обидва refs
# уже свіжі (`git fetch origin +refs/heads/main:… +refs/heads/<гілка>:…`):
# 1.7 с стіни й НУЛЬ об'єктів — `git count-objects -v` до й після дає ті самі
# `in-pack` і `size-pack`, тобто приїжджає саме оголошення ref'ів. Час тут — це
# майже все SSH-рукостискання; байти поштучно не міряні, і це названа межа:
# транспорт цього репо — SSH, а `GIT_TRACE_CURL` міряє лише HTTP, тож міра тут
# — об'єкти, а не байти. Коли гілка рушила, приїжджають її нові об'єкти.
# `--unshallow` додається ТІЛЬКИ до shallow репозиторію (і тоді ціна — вся
# історія): повний репо не платить за нього нічого, і саме тому «репо вже повне
# ⇒ зайвих дій немає» тут не гасло, а межа. Копія — worktree: спільне сховище
# об'єктів, жодного копіювання дерева.
#
# Межі названі тут, у коді, а не лише у звіті:
#   * база — це результат `merge-base` з `origin/main`, і `HEAD` у ній не
#     згадується взагалі. `HEAD` координатора — це не гілка огляду: #1323 саме
#     так дав чужий диф на 77 файлів, і тому локальна гілка з тим самим ім'ям
#     тут теж не читається — огляд не про неї, а про те, що запушено;
#   * `origin/main` оновлюється ЗАВЖДИ, а не лише коли його немає. Застарілий
#     `origin/main` занижує базу і втягує у диф гілки ЧУЖІ коміти main — та
#     сама хибна база, що в #1320, тільки тихіша. Локально застарілість не
#     видно взагалі, тож «fetch, коли треба» тут неможливий без прози;
#     виміряна форма ціни — один обмін (див. «Ціна кроку»);
#   * shallow — це стан, у якому базу НЕ МОЖНА назвати надійно: обрізана
#     історія або не має спільного предка, або має його заниженим (обрізаний
#     коміт виглядає коренем). Тому репо спершу поглиблюється повністю, і якщо
#     це не вдалося — база названа НЕВІДОМОЮ (код 2), а не «як пощастить»;
#   * `merge-base`, якого немає (гілки з різних коренів), — теж код 2 зі своїм
#     ім'ям: вигадати базу тут нема чим, і скрипт цього не робить;
#   * невідомість НЕ лишає копії: копія без названої бази штовхає оглядача до
#     тієї самої команди `…HEAD`, проти якої цей крок і писався. Копія
#     створюється ОСТАННЬОЮ, коли база вже названа;
#   * копія ставиться на РОЗВ'ЯЗАНИЙ sha, а не на ref `origin/<гілка>`: якщо
#     ref поїде між читанням і `worktree add`, надрукована база й дерево
#     лишаться однією ревізією;
#   * та сама ревізія — і в надрукованій команді дифу: вона називає РОЗВ'ЯЗАНІ
#     sha (базу й верхівку), а не рухомий `origin/<гілка>`. Ref рухомий: якщо
#     гілку допушнути під час огляду, диф по ref'у покаже коміти, яких у копії
#     немає, — а копія, база й вердикт мусять бути про ОДНУ ревізію. Це
#     відхилення від прикладу тікета (`git diff <base>...origin/<гілка>`)
#     навмисне, і ціна його названа: пізніший push у надрукованій команді не
#     видно — щоб побачити новіший стан, потрібен повторний виклик. Назва гілки
#     при цьому не губиться: вона стоїть у рядку «копія» поруч із коротким sha;
#   * «немає git» — окремий названий стан, і він перевіряється ПЕРШИМ питанням
#     до git (`--version`): інакше неробочий git дістав би ім'я «ім'я гілки не є
#     іменем ref» — код правильний, а причина ні. Причина відмови
#     `check-ref-format` при цьому друкується, а не переказується;
#   * копія — рівно ця тека, і скрипт не чіпає решту: ні гілок не створює
#     (`--detach`), ні refs не рухає (крім `refs/remotes/origin/…`, які й
#     призначені віддзеркалювати remote), ні чужих worktree не прибирає;
#   * гілку скрипт шукає ЛИШЕ на `origin`. Локальна гілка з тим самим ім'ям —
#     не те, що оглядають, і підставляти її тут означало б повернути #1323
#     тихою половиною; названо прямо, щоб «немає гілки» не читалося як
#     «гілки немає ніде»;
#   * вердикт огляду цей скрипт не ставить і не перевіряє: мітку `review:pass`
#     перепроставляє `scripts/review-pass.sh` (#1259), і змішувати «бачу диф» з
#     «огляд пройдено» тут не можна;
#   * числа в шапці не пінить жоден гейт: `doc_numbers.py` читає лише
#     `docs/agents/*.md` і `scripts/**/*.py` (`AUDIT_FILES`), а `scripts/*.sh`
#     не бачить узагалі. Хто правитиме ці числа — мусить прогнати названу
#     команду сам; машина його не спинить (та сама межа, що в `new-lane.sh`).
#
# Виклик:
#   scripts/review-clone.sh <гілка> [--dir <шлях>]
#
# Типова тека копії — `<репо>/.worktrees/review-<гілка з '/' → '-'>`; `--dir`
# називає іншу. Друкується шлях, у якому команду дифу можна виконати одразу:
# копія — worktree того самого репозиторію, тож `origin/<гілка>` резолвиться
# в ній так само, як у координатора.
#
# Коди виходу:
#   0 — копію створено, база названа;
#   2 — перевірити не вдалося: немає гілки на origin, немає `origin/main`,
#       немає merge-base, немає мережі (origin недосяжний), репо лишилося
#       shallow, тека копії вже зайнята, немає `git`, невідомий аргумент. Кожен
#       випадок названий окремо, і копії по собі не лишається жоден із них.
#       Коду 1 тут немає: прибирати скрипту нічого, тож «є що втрачати» не
#       виникає.
#
# Змінні (ті самі, що в тестах):
#   REVIEW_CLONE_REPO — робоча копія (типово — корінь поточного репозиторію).
set -euo pipefail

GIT="git"
BASE_BRANCH="main"

usage() {
  printf 'usage: scripts/review-clone.sh <гілка> [--dir <шлях>]\n'
  printf '\n'
  printf 'Робить копію для огляду з origin/<гілка> і друкує НАЗВАНУ базу дифу\n'
  printf '(merge-base з origin/main, повним sha), команду дифу, коміти\n'
  printf 'попереду/позаду й те, чи репо shallow і що зроблено, щоб це виправити.\n'
  printf 'Типова тека копії: <репо>/.worktrees/review-<гілка>.\n'
  printf 'Коди виходу: 0 — копію створено, база названа; 2 — невідомість\n'
  printf '(немає гілки, немає origin/main, немає merge-base, немає мережі,\n'
  printf 'shallow лишився, тека зайнята, аргументи).\n'
}

fail() {
  printf 'FAIL  review-clone: %s\n' "$*" >&2
  exit 2
}

# --------------------------------------------------------------------------
# Аргументи
# --------------------------------------------------------------------------

BRANCH=""
DIR=""

while [ "$#" -gt 0 ]; do
  case "$1" in
    -h | --help) usage; exit 0 ;;
    --dir)
      DIR="${2:-}"
      [ -n "$DIR" ] || fail "--dir потребує значення"
      shift 2
      ;;
    -*)
      fail "невідомий прапорець: $1 (спробуй --help)"
      ;;
    *)
      if [ -z "$BRANCH" ]; then
        BRANCH="$1"
      else
        fail "зайвий аргумент: $1"
      fi
      shift
      ;;
  esac
done

[ -n "$BRANCH" ] || fail "не названо гілку (спробуй --help)"
# Приймаємо і `foo`, і `origin/foo`: оглядачеві природно скопіювати ref, який
# він бачив у командах, а не переписувати його руками.
BRANCH="${BRANCH#origin/}"
[ -n "$BRANCH" ] || fail "порожнє ім'я гілки"
# Перше питання до git — «ти взагалі запускаєшся». Без нього неробочий git
# отримав би ім'я «ім'я гілки не є іменем ref» — код правильний, а ІМ'Я ні:
# шапка обіцяє окремий випадок «немає git», і він мусить звучати саме так.
# `--version` не читає ні репозиторію, ні мережі, тож коштує крок у нікуди.
if ! "$GIT" --version >/dev/null 2>&1; then
  fail "немає git: '$GIT' не запускається (git --version не відповів) — без git базу назвати нічим"
fi
# Форму імені перевіряє САМ git (`check-ref-format`), а не власний список
# символів: список відмовив би законній гілці з не-ASCII іменем, тоді як питання
# тут рівно одне — чи можна з цього імені скласти ref. `check-ref-format` не
# потребує репозиторію, тож перевірка стоїть до будь-якого git-читання, а
# причина відмови (stderr самого git) ллється у вивід, а не переказується.
if ! CHECK_REF_OUT="$("$GIT" check-ref-format "refs/heads/$BRANCH" 2>&1)"; then
  fail "ім'я гілки не є іменем ref: '$BRANCH' (git check-ref-format: ${CHECK_REF_OUT:-без пояснень})"
fi

# --------------------------------------------------------------------------
# Робоча копія й тека копії для огляду
# --------------------------------------------------------------------------

REPO="${REVIEW_CLONE_REPO:-}"
if [ -z "$REPO" ]; then
  REPO="$("$GIT" rev-parse --show-toplevel)" ||
    fail "не вдалося знайти корінь робочої копії (немає git?)"
fi
REPO="$(cd "$REPO" 2>/dev/null && pwd)" ||
  fail "робоча копія не знайдена: ${REVIEW_CLONE_REPO:-$REPO}"
if [ ! -d "$REPO/.git" ] && [ ! -f "$REPO/.git" ]; then
  fail "$REPO не є робочою копією git (немає .git)"
fi

if [ -z "$DIR" ]; then
  DIR="$REPO/.worktrees/review-$(printf '%s' "$BRANCH" | tr '/' '-')"
else
  # Відносний `--dir` — від поточного каталогу, як у `git worktree add`, і
  # одразу абсолютний: надрукований шлях мусить бути готовий до копіювання.
  case "$DIR" in
    /*) ;;
    *) DIR="$(pwd)/$DIR" ;;
  esac
fi

REMOTE_REF="refs/remotes/origin/$BRANCH"

# Застарілі записи прибираємо ДО перевірки теки: інакше копія, прибрана
# out-of-band, лишила б «missing but already registered worktree», і наступний
# виклик упав би на власному привиді. `prune` живих записів не чіпає.
"$GIT" -C "$REPO" worktree prune ||
  fail "не вдалося прибрати застарілі записи worktree в $REPO"
if [ -e "$DIR" ]; then
  fail "тека копії вже існує: $DIR — прибери її (git worktree remove '$DIR') або назви іншу через --dir"
fi

# --------------------------------------------------------------------------
# Fetch: рівно один обмін, і --unshallow лише коли репо справді shallow
# --------------------------------------------------------------------------

SHALLOW_BEFORE="$("$GIT" -C "$REPO" rev-parse --is-shallow-repository 2>/dev/null)" ||
  fail "не вдалося прочитати, чи репо shallow (git rev-parse --is-shallow-repository)"
case "$SHALLOW_BEFORE" in
  true | false) ;;
  *) fail "git віддав незрозумілу відповідь на --is-shallow-repository: '$SHALLOW_BEFORE'" ;;
esac

FETCH_ARGS=(fetch origin)
if [ "$SHALLOW_BEFORE" = true ]; then
  FETCH_ARGS+=(--unshallow)
fi
# Явні refspec'и, а не `git fetch origin`: приїжджають рівно дві гілки, і після
# них `refs/remotes/origin/<гілка>` існує гарантовано (+= force: гілку могли
# перезаписати, а оглядати треба те, що на origin ЗАРАЗ).
FETCH_ARGS+=(
  "+refs/heads/$BASE_BRANCH:refs/remotes/origin/$BASE_BRANCH"
  "+refs/heads/$BRANCH:refs/remotes/origin/$BRANCH"
)

set +e
FETCH_OUT="$("$GIT" -C "$REPO" "${FETCH_ARGS[@]}" 2>&1)"
FETCH_CODE=$?
set -e

# Причина невдалого fetch'а називається ДРУГИМ питанням до origin, а не
# розбором тексту помилки: `ls-remote` відповідає і на «чи досяжний origin», і
# на «чи є там ця гілка», трьома різними станами — і кожен має своє ім'я.
remote_heads() {
  "$GIT" -C "$REPO" ls-remote --heads origin 2>&1
}
has_remote_head() {
  printf '%s\n' "$REMOTE_HEADS" | awk -v ref="refs/heads/$1" '$2 == ref { found = 1 } END { exit !found }'
}

if [ "$FETCH_CODE" -ne 0 ]; then
  REMOTE_HEADS="$(remote_heads)" || REMOTE_HEADS=""
  if [ -z "$REMOTE_HEADS" ]; then
    if [ "$SHALLOW_BEFORE" = true ]; then
      fail "немає мережі: origin недосяжний, а репо shallow — історію поглибити нічим, базу назвати не можна. git казав: $(printf '%s' "$FETCH_OUT" | tail -n 2 | tr '\n' ' ')"
    fi
    fail "немає мережі: origin недосяжний (git fetch і git ls-remote обидва не відповіли). git казав: $(printf '%s' "$FETCH_OUT" | tail -n 2 | tr '\n' ' ')"
  fi
  if ! has_remote_head "$BASE_BRANCH"; then
    fail "немає origin/main: на origin немає гілки '$BASE_BRANCH' — базу взяти нізвідки"
  fi
  if ! has_remote_head "$BRANCH"; then
    fail "немає гілки: origin не має refs/heads/$BRANCH (перевір ім'я або чи запушено гілку; локальна гілка тут не читається)"
  fi
  fail "git fetch не вдався, хоч обидві гілки на origin є. git казав: $(printf '%s' "$FETCH_OUT" | tail -n 3 | tr '\n' ' ')"
fi

SHALLOW_AFTER="$("$GIT" -C "$REPO" rev-parse --is-shallow-repository 2>/dev/null)" || SHALLOW_AFTER="unknown"
case "$SHALLOW_AFTER" in
  true) fail "репо лишилося shallow навіть після --unshallow — база тут непевна, і скрипт її не вигадує" ;;
  false) ;;
  *) fail "після fetch'а не вдалося перечитати, чи репо shallow (git віддав '$SHALLOW_AFTER')" ;;
esac

# --------------------------------------------------------------------------
# База: merge-base з origin/main, і жодного HEAD
# --------------------------------------------------------------------------

BASE_SHA="$("$GIT" -C "$REPO" rev-parse --verify "refs/remotes/origin/$BASE_BRANCH^{commit}" 2>/dev/null)" ||
  fail "не вдалося прочитати origin/$BASE_BRANCH після fetch'а"
TIP_SHA="$("$GIT" -C "$REPO" rev-parse --verify "$REMOTE_REF^{commit}" 2>/dev/null)" ||
  fail "немає гілки: $REMOTE_REF не резолвиться після fetch'а"

set +e
MERGE_BASE="$("$GIT" -C "$REPO" merge-base "$BASE_SHA" "$TIP_SHA" 2>/dev/null)"
MERGE_CODE=$?
set -e
if [ "$MERGE_CODE" -ne 0 ] || [ -z "$MERGE_BASE" ]; then
  fail "немає merge-base: у origin/$BASE_BRANCH і origin/$BRANCH немає спільної історії — базу назвати нічим (копії не створено)"
fi
# Повний sha — обіцянка виводу, а не побажання: обрізану відповідь тут не можна
# видати за базу, бо саме за нею оглядач побудує диф.
#
# Порожня альтернатива (`'' |` у `case`) тут НЕ стоїть навмисно, і це не
# послаблення: порожній `MERGE_BASE` уже відсіяно вище (`-z` у перевірці коду
# виходу), тож `''` у шаблоні був би мертвою гілкою — а мертва перевірка, яку
# ніщо не виробляє, це те саме «зелене ні про що», проти якого стоїть
# `empty_shape_mutants.py`. Порожнє значення ловить перевірка ДОВЖИНИ нижче.
case "$MERGE_BASE" in
  *[!0-9a-f]*) fail "merge-base віддав не sha: '$MERGE_BASE'" ;;
esac
if [ "${#MERGE_BASE}" -ne 40 ]; then
  fail "merge-base віддав не ПОВНИЙ sha (${#MERGE_BASE} символів): '$MERGE_BASE'"
fi

MERGE_SHORT="${MERGE_BASE:0:8}"
TIP_SHORT="$("$GIT" -C "$REPO" rev-parse --short "$TIP_SHA")"

# Попереду/позаду — від верхівки origin/main, як у `check-base-sync.sh`: це
# те, що оглядач бачить у PR, а не відстань до точки розходження.
AHEAD="$("$GIT" -C "$REPO" rev-list --count "$BASE_SHA..$TIP_SHA" 2>/dev/null)" ||
  fail "не вдалося порахувати коміти попереду"
BEHIND="$("$GIT" -C "$REPO" rev-list --count "$TIP_SHA..$BASE_SHA" 2>/dev/null)" ||
  fail "не вдалося порахувати коміти позаду"
# Порожній лічильник ловиться тим самим шаблоном, і без мертвої `''`: шаблон
# `^[0-9]+$` не збігається ні з порожнім рядком, ні з нечислом, тож одна
# перевірка називає обидва стани.
for count in "$AHEAD" "$BEHIND"; do
  printf '%s' "$count" | grep -qE '^[0-9]+$' ||
    fail "лічильник комітів не число: '$count' (попереду '$AHEAD', позаду '$BEHIND')"
done

# --------------------------------------------------------------------------
# Копія — ОСТАННЬОЮ: невідомість не лишає по собі копії без названої бази
# --------------------------------------------------------------------------

# Вивід `worktree add` («Preparing worktree…») у нормальному випадку не
# потрібен: факти друкуються нижче, а шум у кроці, який кличуть щодня, — це те,
# через що гейти обходять. На помилці він, навпаки, показується повністю.
set +e
WORKTREE_OUT="$("$GIT" -C "$REPO" worktree add --detach "$DIR" "$TIP_SHA" 2>&1)"
WORKTREE_CODE=$?
set -e
if [ "$WORKTREE_CODE" -ne 0 ]; then
  # Відкат — рівно те, що створив ЦЕЙ прогін, і рівно якщо це ЗАРЕЄСТРОВАНИЙ
  # worktree: невдалий `worktree add` лишає по собі напівкопію, на яку наступний
  # виклик упав би «тека вже існує». Теки, якої git не зареєстрував, скрипт не
  # чіпає: якщо шлях з'явився між перевіркою й `add`, це чужа тека, і `rm -rf`
  # по ній був би знищенням не свого — тому такий стан названо, а не прибрано.
  if "$GIT" -C "$REPO" worktree list --porcelain 2>/dev/null | grep -Fxq "worktree $DIR"; then
    if "$GIT" -C "$REPO" worktree remove --force "$DIR" 2>/dev/null; then
      fail "git worktree add не вдався ($(printf '%s' "$WORKTREE_OUT" | tail -n 2 | tr '\n' ' ')) — напівкопію прибрано, копії немає"
    fi
    fail "git worktree add не вдався, і напівкопію $DIR прибрати не вдалося — прибери її руками (git worktree remove --force '$DIR')"
  fi
  fail "git worktree add не вдався ($(printf '%s' "$WORKTREE_OUT" | tail -n 2 | tr '\n' ' ')) — копії не створено; зареєстрованого worktree немає, і чужого шляху скрипт не чіпає"
fi

# --------------------------------------------------------------------------
# Факти: їх вставляють, а не згадують
# --------------------------------------------------------------------------

printf 'копія: %s (origin/%s, %s)\n' "$DIR" "$BRANCH" "$TIP_SHORT"
printf 'база: %s (%s) — merge-base origin/%s...origin/%s\n' \
  "$MERGE_SHORT" "$MERGE_BASE" "$BASE_BRANCH" "$BRANCH"
printf 'коміти: попереду %s, позаду %s (origin/%s)\n' "$AHEAD" "$BEHIND" "$BASE_BRANCH"
if [ "$SHALLOW_BEFORE" = true ]; then
  printf 'shallow: так — зроблено `git fetch --unshallow origin` (обидві гілки, історію поглиблено повністю)\n'
else
  printf 'shallow: ні — зайвих дій не робив (ні --unshallow, ні решти гілок)\n'
fi
# Диф — по РОЗВ'ЯЗАНИХ sha (база й верхівка), а не по `origin/<гілка>`. Ref
# рухомий: якщо гілку допушнути під час огляду, диф по ref'у покаже коміти, яких
# у копії немає, — і «копія», «база» та вердикт перестануть бути про одну
# ревізію. Назва гілки лишається в рядку «копія», тож читається, що це за гілка.
printf 'диф: git diff %s...%s\n' "$MERGE_BASE" "$TIP_SHA"
printf 'прибрати: git worktree remove %s\n' "$DIR"
