#!/usr/bin/env bash
#
# Правильний спосіб дешевший за неправильний: код виходу, який не бреше.
#
# Навіщо. `cmd | tail` віддає код `tail`, а не команди. Сесія прочитала `exit 0`
# чотири рази, коли в лозі стояло `BUILD FAILED` — і кожен раз це виглядало як
# успіх. Рецепт `(cmd > log 2>&1; echo $? > exit)` записаний у
# `docs/agents/local-environment.md`, але це cure, не захист: знати його треба
# ЗАЗДАЛЕГІДЬ, а забути — легко.
#
# Цей скрипт робить правильне найкоротшим шляхом:
#   * команда виконується БЕЗ конвеєра, тож `$?` — це її код, не чужий;
#   * вивід іде і на екран (через `tee`), і у файл логу;
#   * код виходу друкується останнім рядком і лежить у файлі.
#
# Використання:
#   scripts/run.sh -- <команда> [аргументи...]
#   scripts/run.sh --name build -- ./gradlew :app:assembleDebug --no-daemon
#
# Опції:
#   --name <ім'я>   ім'я для логу (типово: run)
#   --log <шлях>    шлях до логу (типово: .run/<ім'я>.log)
#
# Коди виходу: код команди. 2 — неправильний виклик (немає `--`).
#
# `set -o pipefail` тут НЕ потрібен і не використовується: конвеєра немає.

set -uo pipefail

NAME="run"
LOG=""

while [ $# -gt 0 ]; do
    case "$1" in
        --name) NAME="${2:-}"; shift 2 ;;
        --log)  LOG="${2:-}"; shift 2 ;;
        --)     shift; break ;;
        *)      echo "run: очікую '--' перед командою (отримав '$1')" >&2; exit 2 ;;
    esac
done

if [ $# -eq 0 ]; then
    echo "run: немає команди. Використання: scripts/run.sh -- <команда> [аргументи...]" >&2
    exit 2
fi

[ -n "$LOG" ] || LOG=".run/$NAME.log"
mkdir -p "$(dirname "$LOG")"
EXIT_FILE="${LOG%.log}.exit"

# Ось серце: команда біжить САМА, без конвеєра, тому `$?` після неї — код САМОЇ
# команди, а не чужої. Вивід іде у файл, а потім файл друкується.
#
# ЧОМУ НЕ `tee` І НЕ `> >(tee)`: обидва варіанти зламані тут.
#   * `"$@" | tee "$LOG"` — `$?` стає кодом `tee`, тобто рівно та помилка, проти
#     якої цей скрипт існує;
#   * `"$@" > >(tee "$LOG")` — підстановка процесу асинхронна, і скрипт виходив
#     РАНІШЕ, ніж `tee` дописував: лог лишався порожнім (перевірено — порожній).
# Синхронний запис у файл коштує втрати живого потоку, але не бреше.
"$@" > "$LOG" 2>&1
CODE=$?
cat "$LOG"

echo "$CODE" > "$EXIT_FILE"
echo "run: код виходу $CODE (лог: $LOG, код: $EXIT_FILE)"
exit "$CODE"
